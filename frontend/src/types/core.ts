import { z } from 'zod';
export const roleSchema = z.enum(['STUDENT','TEACHER','METHODIST','ADMIN']);
export const courseStatusSchema = z.enum(['DRAFT','PUBLISHED','ARCHIVED']);
export const lessonTypeSchema = z.enum(['TEXT','VIDEO','QUIZ','CODE']);
export const attemptStatusSchema = z.enum(['IN_PROGRESS','FINISHED','EXPIRED']);
const id = z.number().int().safe();
const text = z.string().nullable();
const integer = z.number().int().nullable();
const timestamp = z.string().nullable();
export const userSchema = z.object({id,email:z.string(),fullName:z.string(),role:roleSchema,isEnabled:z.boolean().nullable(),createdAt:timestamp,updatedAt:timestamp});
export const courseSchema = z.object({id,teacherId:id,title:z.string(),category:text,description:text,status:courseStatusSchema,createdAt:timestamp,updatedAt:timestamp});
export const courseSearchSchema = z.object({id,title:z.string(),description:text,category:text,status:z.string(),teacherId:id,teacherName:text});
export const courseModuleSchema = z.object({id,courseId:id,title:z.string(),orderIndex:integer,createdAt:timestamp});
export const enrollmentSchema = z.object({id,userId:id,courseId:id,progressPct:integer,enrolledAt:timestamp});
export const lessonSchema = z.object({id,moduleId:id,type:lessonTypeSchema,title:z.string(),content:text,orderIndex:integer,createdAt:timestamp});
export const lessonProgressSchema = z.object({id:id.nullable(),enrollmentId:id,lessonId:id,completedAt:timestamp,score:integer});
export const materialSchema = z.object({id,lessonId:id,fileName:z.string(),contentType:text,sizeBytes:z.number().nullable(),uploadedAt:timestamp});
export const examSchema = z.object({id,lessonId:id,title:text,timeLimitMinutes:integer});
export const examQuestionSchema = z.object({id,question:text,maxScore:integer,orderIndex:integer});
export const examAnswerSchema = z.object({questionId:id,question:text,answer:text,score:integer,feedback:text,maxScore:integer});
// These DTOs declare String status, not AttemptStatus. Retain unknown future strings safely.
export const examAttemptSchema = z.object({attemptId:id,examId:id,startedAt:timestamp,finishedAt:timestamp,totalScore:integer,status:z.string(),answers:z.array(examAnswerSchema).nullable()});
export const examProgressSchema = z.object({examId:id,examTitle:text,score:integer,status:z.string()});
export const examWebSocketSchema = z.object({attemptId:id,status:z.string(),remainingSeconds:z.number().int(),startedAt:timestamp,deadline:timestamp});
export const forumPostSchema = z.object({id,topicId:id,authorId:id,authorName:text,content:z.string(),createdAt:timestamp});
export const forumTopicSchema = z.object({id,courseId:id,authorId:id,authorName:text,title:z.string(),createdAt:timestamp,updatedAt:timestamp,posts:z.array(forumPostSchema).nullable()});
export const lessonAnalyticsSchema = z.object({lessonId:id,lessonTitle:text,completedStudents:integer,totalStudents:integer,completionPercent:integer});
export const studentProgressSchema = z.object({courseId:id,courseTitle:text,progressPercent:z.number().nullable(),completedLessons:integer,totalLessons:integer,lessons:z.array(lessonProgressSchema).nullable(),exams:z.array(examProgressSchema).nullable()});
export const teacherAnalyticsSchema = z.object({courseId:id,courseTitle:text,totalStudents:integer,completedStudents:integer,averageProgress:z.number().nullable(),averageExamScore:z.number().nullable(),lessons:z.array(lessonAnalyticsSchema).nullable()});
export const askSchema = z.object({answer:text,sources:z.array(z.string()).nullable()});
export const aiGradeSchema = z.object({questionId:id,score:integer,feedback:text});
export const aiQuestionSchema = z.object({question:text,maxScore:integer});
export const apiErrorSchema = z.object({timestamp:z.string(),status:z.number().int(),error:z.string(),message:z.string(),path:z.string()});
export type Role = z.infer<typeof roleSchema>;
export type CourseStatus = z.infer<typeof courseStatusSchema>;
export type LessonType = z.infer<typeof lessonTypeSchema>;
export type AttemptStatus = z.infer<typeof attemptStatusSchema>;
export type UserResponse = z.infer<typeof userSchema>;
export type CourseResponse = z.infer<typeof courseSchema>;
export type CourseSearchResponse = z.infer<typeof courseSearchSchema>;
export type CourseModuleResponse = z.infer<typeof courseModuleSchema>;
export type EnrollmentResponse = z.infer<typeof enrollmentSchema>;
export type LessonResponse = z.infer<typeof lessonSchema>;
export type LessonProgressResponse = z.infer<typeof lessonProgressSchema>;
export type MaterialResponse = z.infer<typeof materialSchema>;
export type ExamResponse = z.infer<typeof examSchema>;
export type ExamQuestionResponse = z.infer<typeof examQuestionSchema>;
export type ExamAnswerResponse = z.infer<typeof examAnswerSchema>;
export type ExamAttemptResponse = z.infer<typeof examAttemptSchema>;
export type ExamProgressResponse = z.infer<typeof examProgressSchema>;
export type ExamWebSocketResponse = z.infer<typeof examWebSocketSchema>;
export type ForumPostResponse = z.infer<typeof forumPostSchema>;
export type ForumTopicResponse = z.infer<typeof forumTopicSchema>;
export type LessonAnalyticsResponse = z.infer<typeof lessonAnalyticsSchema>;
export type StudentProgressResponse = z.infer<typeof studentProgressSchema>;
export type TeacherCourseAnalyticsResponse = z.infer<typeof teacherAnalyticsSchema>;
export type AskResponse = z.infer<typeof askSchema>;
export type AiGradeResponse = z.infer<typeof aiGradeSchema>;
export type AiQuestionResponse = z.infer<typeof aiQuestionSchema>;
export type ApiErrorResponse = z.infer<typeof apiErrorSchema>;
